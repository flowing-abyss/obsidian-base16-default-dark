// Snapshot of custom-property names that resolve to a non-empty value in a
// running Obsidian instance, used by check-vars.mjs to recognise a var(--x)
// reference in our own CSS as "Obsidian-supplied" rather than dangling.
//
// How this list was obtained (reproducible manually, not scripted, because
// it needs a live app and the check itself must run without one):
//   1. Open the vault this theme develops against in Obsidian (1.13.7 at
//      capture time), with community plugins and snippets in their normal
//      enabled state, and switch Settings > Appearance > Theme to
//      "Default" so this theme's own --b16-*/token declarations are not
//      loaded and cannot leak into the sample.
//   2. In the console (`obsidian eval`), read
//      `getComputedStyle(document.body)`, iterate every custom-property
//      name it exposes, and keep only the ones whose
//      `getPropertyValue(name)` is non-empty. A name can be *declared*
//      (e.g. Obsidian's own `body { --h1-color: inherit }`) without ever
//      resolving to anything, because `inherit`/`initial`/`unset`/`revert`
//      are CSS-wide keywords and are guaranteed-invalid as a custom
//      property's value — that declaration is silently dropped by the
//      engine. Filtering on the *computed*, non-empty value (not on which
//      names merely appear in a declaration) is what catches that case;
//      it is exactly how `--h1-color` and `--inline-title-color` were
//      excluded from this list even though app.css contains a rule that
//      looks like it defines them.
//   3. Switch the theme back to "Base16 Default Dark" and reload.
//
// This snapshot therefore also includes variables supplied by whichever
// community plugins were active in that vault at capture time (e.g. the
// `--aqs-*` family from Another Quick Switcher) — that is intentional and
// desirable: those variables genuinely resolve in the environment this
// theme ships into. A plugin variable that is referenced by our CSS but did
// NOT happen to be present at capture time (conditionally supplied, or from
// a plugin not installed in the capture vault) belongs in the exemption
// list in check-vars.mjs instead, with a reason.
//
// Re-capture by repeating the steps above if Obsidian's own variable set
// changes across a major app version and check:vars starts failing on
// names that look like core Obsidian variables.
